"""Regenerate the five Chinese OSD labels as 128x16 bitmaps.

Emits both rtl/cnn_expression_text.v and assets/cnn_expression/label_masks.hex so
the golden reference used by tests/expression_text_tb.v always matches the RTL.

Layout: the panel is 128 px wide. ASCII advances 8 px, CJK advances 16 px, so a
label such as "taffy-哭哭" (6 ASCII + 2 CJK) occupies 6*8 + 2*16 = 80 px.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
LABELS = ["无法确定", "taffy-大笑", "taffy-放松", "taffy-哭哭", "taffy-微笑"]
W, H = 128, 16
FONT = r"C:\Windows\Fonts\msyh.ttc"
CJK_SIZE = 14
ASCII_SIZE = 13
CJK_ADV, ASCII_ADV = 16, 8


def cell_bitmap(ch, width, size):
    """Render one glyph into a width x 16 mono bitmap, ink = True."""
    font = ImageFont.truetype(FONT, size)
    img = Image.new("L", (width, H), 255)
    d = ImageDraw.Draw(img)
    box = d.textbbox((0, 0), ch, font=font)
    w, h = box[2] - box[0], box[3] - box[1]
    x = (width - w) // 2 - box[0]
    y = (H - h) // 2 - box[1]
    d.text((x, y), ch, font=font, fill=0)
    px = img.load()
    return [[px[cx, cy] < 128 for cx in range(width)] for cy in range(H)]


def label_rows(text):
    """128x16 bitmap rows, True = ink."""
    rows = [[False] * W for _ in range(H)]
    ox = 0
    for ch in text:
        ascii_char = ord(ch) < 128
        w = ASCII_ADV if ascii_char else CJK_ADV
        if ox + w > W:
            break
        bm = cell_bitmap(ch, w, ASCII_SIZE if ascii_char else CJK_SIZE)
        for cy in range(H):
            for cx in range(w):
                if bm[cy][cx]:
                    rows[cy][ox + cx] = True
        ox += w
    return rows


def main():
    masks = []
    verilog_rows = []
    for cls, text in enumerate(LABELS):
        rows = label_rows(text)
        for cy in range(H):
            value = 0
            for cx in range(W):
                if rows[cy][cx]:
                    value |= 1 << (W - 1 - cx)
            verilog_rows.append((cls * H + cy, value))
            masks.extend("1" if rows[cy][cx] else "0" for cx in range(W))

    (ROOT / "assets/cnn_expression/label_masks.hex").write_text(
        "\n".join(masks) + "\n", encoding="ascii")

    lines = [
        "// Generated by tools/make_cnn_expression_text.py. No inferred framebuffer.",
        "// labels: 0 unknown, 1 taffy-laugh, 2 taffy-relax, 3 taffy-cry, 4 taffy-smile",
        "module cnn_expression_text #(",
        "    parameter integer WIDTH=1920,HEIGHT=1080,",
        "    parameter integer SCALE=WIDTH>=640 ? 4:1",
        ")(input [11:0] x,y,input [2:0] class_id,output ink,panel);",
        "    localparam LEFT=(WIDTH-128*SCALE)/2,TOP=HEIGHT>=256 ? 64:16;",
        "    wire [11:0] dx=x-LEFT,dy=y-TOP;",
        "    wire [6:0] tx=dx/SCALE;",
        "    wire [3:0] ty=dy/SCALE;",
        "    wire [2:0] safe_class=class_id<=4 ? class_id:3'd0;",
        "    wire [6:0] address={safe_class,ty};",
        "    reg [127:0] row_bits;",
        "    always @* begin",
        "        row_bits=0;",
        "        case(address)",
    ]
    for addr, value in verilog_rows:
        lines.append(f"            7'd{addr}:row_bits=128'h{value:032x};")
    lines += [
        "            default:row_bits=0;",
        "        endcase",
        "    end",
        "    assign panel=x>=LEFT && dx<128*SCALE && y>=TOP && dy<16*SCALE;",
        "    assign ink=panel && row_bits[127-tx];",
        "endmodule",
        "",
    ]
    (ROOT / "rtl/cnn_expression_text.v").write_text("\n".join(lines), encoding="utf-8")

    prev = Image.new("L", (W, H * len(LABELS)), 0)
    for cls, text in enumerate(LABELS):
        rows = label_rows(text)
        for cy in range(H):
            for cx in range(W):
                prev.putpixel((cx, cls * H + cy), 255 if rows[cy][cx] else 0)
    (ROOT / "previews").mkdir(exist_ok=True)
    prev.resize((W * 6, H * len(LABELS) * 6), Image.NEAREST).save(
        ROOT / "previews/labels_preview.png")

    for cls, text in enumerate(LABELS):
        used = sum(1 for cx in range(W) if any(label_rows(text)[cy][cx] for cy in range(H)))
        print(f"class {cls}: {text!r}  宽 {used} px")


if __name__ == "__main__":
    main()
